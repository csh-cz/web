#!/usr/bin/env node
/**
 * Auto-link první zmínky každého hodinového kroku v MD/MDX těle článku
 * na příslušnou kartu /kroky/<slug>.
 *
 * Princip:
 *   1. Načte slugy + aliasy z apps/hodinarium-eu/src/data/kroky.ts.
 *   2. Pro každý článek (content/hodinarium-eu/, content/hodinari/,
 *      content/soupis-veznich-hodin/) projde body (mimo frontmatter).
 *   3. Pro každý krok najde PRVNÍ výskyt aliasu (case-sensitive, word
 *      boundary), který NENÍ:
 *        - už v Markdown linku (regex `[...](...)` lookbehind/ahead)
 *        - v code-blocku ` ``` ` nebo inline `code`
 *        - v nadpisu (řádek začínající '#')
 *        - v citaci v `references:` frontmatter
 *   4. Zabalí ho do [<text>](/kroky/<slug>). Bold-ové **alias** zachová
 *      uvnitř linku: **[alias](/kroky/<slug>)**.
 *
 * Použití:
 *   node scripts/auto-link-kroky.mjs --dry-run    # report bez změn
 *   node scripts/auto-link-kroky.mjs              # apply
 *
 * Bezpečnost: aplikuje JEN první zmínku v souboru per krok. Tj. když
 * článek zmiňuje Grahamův krok 5×, jen první se zlinkuje. Žádný
 * link-spam.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const ROOT = join(dirname(__filename), '..');
const DRY_RUN = process.argv.includes('--dry-run');

// Načti slugy + aliasy z kroky.ts
const krokyTs = readFileSync(join(ROOT, 'apps/hodinarium-eu/src/data/kroky.ts'), 'utf8');
// Parse blocky `{ slug: '…', jmeno: '…', aliasy: ['…', '…', …], … }`.
// Tady stačí regex — kroky.ts je strukturovaně předvídatelný (auto-generated by hand).
const krokBlocks = [...krokyTs.matchAll(/{\s*slug:\s*['"]([^'"]+)['"][\s\S]*?aliasy:\s*\[([^\]]+)\]/g)];
const kroky = krokBlocks.map((m) => ({
  slug: m[1],
  aliasy: [...m[2].matchAll(/['"]([^'"]+)['"]/g)].map((mm) => mm[1]),
}));

console.log(`Načteno ${kroky.length} kroků z kroky.ts:`);
for (const k of kroky) console.log(`  ${k.slug.padEnd(40)} ${k.aliasy.length} aliasů`);
console.log('');

// Soubory ke kontrole
const dirs = ['content/hodinarium-eu', 'content/hodinari', 'content/soupis-veznich-hodin'];
const files = [];
for (const d of dirs) {
  const full = join(ROOT, d);
  try {
    for (const f of readdirSync(full)) {
      if (/\.(md|mdx)$/.test(f)) files.push(join(full, f));
    }
  } catch { /* missing dir */ }
}
console.log(`Soubory ke kontrole: ${files.length}\n`);

// Heuristika: oddělit frontmatter (pokud je) od body
function splitFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) return { fm: '', body: text };
  return { fm: m[0], body: text.slice(m[0].length) };
}

// Kontrola, zda pozice není v linku [...](url) / inline `code` / heading.
function isInProtectedContext(body, idx) {
  // Hledej `]` před a `(` po — pokud je to mezi nimi v linku [...] (...) ne.
  // Praktičtěji: testuj zda je `idx` uvnitř `(...)` po `]`.
  const around = body.slice(Math.max(0, idx - 200), idx + 200);
  const pos = idx - Math.max(0, idx - 200);
  // 1. Inside markdown link: `[...](...)`. Test: před idx hledá `](` , po idx hledá `)`.
  const beforeOpenParen = around.lastIndexOf('](', pos);
  const beforeCloseParen = around.lastIndexOf(')', pos);
  if (beforeOpenParen > beforeCloseParen) {
    // We're inside `(…)` part of a link
    return true;
  }
  // 2. Inside link text [...]: před idx '[' (žádný ']'), po idx ']'.
  const beforeOpenBracket = around.lastIndexOf('[', pos);
  const beforeCloseBracket = around.lastIndexOf(']', pos);
  const afterCloseBracket = around.indexOf(']', pos);
  if (beforeOpenBracket > beforeCloseBracket && afterCloseBracket > pos) {
    // We're inside [...] text
    return true;
  }
  // 3. Inline code `…`
  // Count backticks before idx; if odd, we're in code
  const beforeText = body.slice(0, idx);
  // Skip code blocks ``` first
  const blockOpens = (beforeText.match(/```/g) || []).length;
  if (blockOpens % 2 === 1) return true; // inside ``` block
  // Now count single backticks (rough heuristic)
  const singleBackticks = (beforeText.match(/(?<!`)`(?!`)/g) || []).length;
  if (singleBackticks % 2 === 1) return true;
  // 4. Heading (line begins with #)
  const lineStart = body.lastIndexOf('\n', idx) + 1;
  const lineSlice = body.slice(lineStart, idx);
  if (/^#{1,6}\s/.test(lineSlice)) return true;
  return false;
}

// Filter aliasy na high-precision pro auto-link. Ambiguous single words
// jako "Graham" (kdo?), "kotva" (část jiných kroků), "vřeteno", "anchor"
// vyloučit — match na ně by linkoval i v cizích kontextech.
//
// Povoleno:
//   - přídavná jména s českou koncovkou (-ův/-ova/-ovým/-ové/-ovou)
//   - cokoli s "krok" / "krokem" / "kroku"
//   - multi-word fráze
//   - exkluzivní termíny (přerušovač, oscilátor)
function isLinkSafeAlias(alias) {
  if (/\s/.test(alias)) return true; // multi-word
  if (/krok|krokem|kroku/i.test(alias)) return true;
  if (/(ův|ova|ovým|ové|ovou)$/i.test(alias)) return true;
  if (/(přerušovač|oscilátor|retrográdní)/i.test(alias)) return true;
  return false;
}

// Specific vs generic — specific se linkuje vždy první, aby na řádku byl
// link kontextu pro generic-on-specific check (jinak by generic alias
// "kotvový krok" matchnul před "Grahamův" jen kvůli délce a oba by se
// zalinkovaly).
const SPECIFIC_KROKY = new Set([
  'robertuv-krok', 'grahamuv-krok', 'amantuv-krok',
  'hippuv-prerusovac', 'retrogradni-zobrazovani',
  'elektronicky-krok', 'elektronicky-mikroprocesorovy-krok',
]);
const GENERIC_KROKY = new Set(['kotvovy-krok', 'vretenovy-krok']);

// Build prioritized alias list — specific kroky první, pak delší aliasy.
const aliases = [];
for (const krok of kroky) {
  for (const alias of krok.aliasy) {
    if (!isLinkSafeAlias(alias)) continue;
    aliases.push({ slug: krok.slug, alias, len: alias.length });
  }
}
aliases.sort((a, b) => {
  const aGen = GENERIC_KROKY.has(a.slug) ? 1 : 0;
  const bGen = GENERIC_KROKY.has(b.slug) ? 1 : 0;
  if (aGen !== bGen) return aGen - bGen; // specific first
  return b.len - a.len; // pak delší alias první
});

console.log(`High-precision aliasy: ${aliases.length} (po filtru z ${kroky.reduce((s, k) => s + k.aliasy.length, 0)})`);

// Apply per-file
let totalLinks = 0;
let filesModified = 0;
const report = [];

for (const file of files) {
  const orig = readFileSync(file, 'utf8');
  const { fm, body } = splitFrontmatter(orig);
  let workBody = body;
  const linkedSlugs = new Set();

  // (SPECIFIC_KROKY a GENERIC_KROKY jsou definované mimo loop, nahoře.)

  for (const { slug, alias } of aliases) {
    if (linkedSlugs.has(slug)) continue; // už zalinkováno (jinou aliasu)
    // Word-boundary match — alias musí být ohraničený nealfanumerickým znakem
    // nebo začátkem/koncem řetězce. Diakritiku počítáme jako alfa.
    // Použijeme negativní lookbehind/lookahead pro \p{L}\p{N}_.
    const escapedAlias = alias.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const re = new RegExp(`(?<![\\p{L}\\p{N}_])${escapedAlias}(?![\\p{L}\\p{N}_])`, 'u');
    const m = re.exec(workBody);
    if (!m) continue;
    const idx = m.index;
    if (isInProtectedContext(workBody, idx)) continue;

    // Generic-on-specific check: na stejném řádku už specific krok zlinkován?
    if (GENERIC_KROKY.has(slug)) {
      const lineStart = workBody.lastIndexOf('\n', idx) + 1;
      const lineEnd = workBody.indexOf('\n', idx);
      const line = workBody.slice(lineStart, lineEnd === -1 ? workBody.length : lineEnd);
      const hasSpecific = [...SPECIFIC_KROKY].some((s) => line.includes(`/kroky/${s}`));
      if (hasSpecific) continue;
    }

    // Zabal do markdown linku. Tři případy:
    //   (1) Alias je tightly v **alias** (pre/post `**`) → zachovej bold okolo
    //   (2) Alias je uvnitř existujícího bold range (např. **alias kolíčkovým krokem**)
    //       → vlastní `**` wrap by způsobil 4× `**` bug. Replacement je jen
    //       `[alias](url)` bez `**`.
    //   (3) Plain text → `**[alias](url)**`
    const before = workBody.slice(Math.max(0, idx - 2), idx);
    const after = workBody.slice(idx + alias.length, idx + alias.length + 2);
    const beforeText = workBody.slice(0, idx);
    const boldsBeforeIdx = (beforeText.match(/\*\*/g) || []).length;
    const insideExistingBold = boldsBeforeIdx % 2 === 1;
    let replacement;
    if (before === '**' && after === '**') {
      // Tight **alias** → [alias](url) (zachovej bold, jen vlož link uvnitř)
      replacement = `[${alias}](/kroky/${slug})`;
    } else if (insideExistingBold) {
      // Alias je uvnitř existujícího bold range (např. **... alias ...**)
      // Vlastní `**` wrap by stvořil čtveřici → jen plain link bez bold.
      replacement = `[${alias}](/kroky/${slug})`;
    } else {
      // Plain alias → **[alias](url)**
      replacement = `**[${alias}](/kroky/${slug})**`;
    }
    workBody = workBody.slice(0, idx) + replacement + workBody.slice(idx + alias.length);
    linkedSlugs.add(slug);
    totalLinks++;
    const lineStart = body.slice(0, idx).split('\n').length;
    report.push({ file: file.replace(`${ROOT}/`, ''), line: lineStart, slug, alias });
  }

  if (workBody !== body) {
    filesModified++;
    if (!DRY_RUN) {
      writeFileSync(file, fm + workBody, 'utf8');
    }
  }
}

console.log(`\n=== Výsledek ${DRY_RUN ? '(DRY RUN)' : '(APPLIED)'} ===`);
console.log(`Souborů upraveno: ${filesModified}`);
console.log(`Linků přidáno:    ${totalLinks}\n`);

// Per-slug rozpis
const bySlug = {};
for (const r of report) {
  bySlug[r.slug] = (bySlug[r.slug] || 0) + 1;
}
for (const [slug, n] of Object.entries(bySlug).sort((a, b) => b[1] - a[1])) {
  console.log(`  ${slug.padEnd(40)} ${n}`);
}

if (process.argv.includes('-v') || DRY_RUN) {
  console.log('\nDetail:');
  for (const r of report.slice(0, 80)) {
    console.log(`  ${r.file}:${r.line}  →  /${r.slug}  ("${r.alias}")`);
  }
  if (report.length > 80) console.log(`  ... +${report.length - 80} dalších`);
}

if (DRY_RUN) {
  console.log('\nDry run — žádné změny zapsány. Run bez --dry-run pro apply.');
}
